//! The shared tool configs, built from a repo's `.stet.toml`. This is the one copy of the
//! setup that each knowledge repo used to carry by hand. `stet sync` writes these files and
//! `stet check` fails when a repo's copy differs, so CI, which can't run stet, still runs
//! the tools on exactly this config.
//!
//! Two files keep a part that belongs to the repo: `.cspell.yaml` from `words:` on (the
//! repo's vocabulary) and `.mise.toml` below [`MISE_MARKER`] (the repo's own tasks).

use crate::config::{Ignore, RepoConfig, Tool};

pub const HEADER: &str = "# Generated by stet from .stet.toml. Edit that file and run `stet sync`.";

/// Everything below this line in `.mise.toml` is the repo's own.
pub const MISE_MARKER: &str =
    "# ---- Below this line: this repo's own tasks. stet sync leaves them as they are. ----";

pub const NODE: &str = "24.4.1";
pub const CSPELL: &str = "9.1.5";
pub const PRETTIER: &str = "3.8.3";
pub const MARKDOWNLINT: &str = "0.22.1";

/// Ignores every repo gets, for every tool and the house rules.
pub fn shared_ignores() -> Vec<Ignore> {
    let entry = |paths: &[&str], reason: &str| Ignore {
        paths: paths.iter().map(|p| p.to_string()).collect(),
        tools: None,
        reason: reason.into(),
    };
    vec![
        entry(&["node_modules/"], "Installed packages."),
        entry(
            &["Inbox/"],
            "The drop zone holds raw captures, not records. Never reformatted or linted in \
             place; checked once absorbed into a domain.",
        ),
        entry(
            &["**/.build/"],
            "SwiftPM build output and checkouts: other people's code.",
        ),
    ]
}

/// Files cspell skips in every repo: binary formats with no prose to check.
const BINARY: [&str; 13] = [
    "pdf", "doc", "docx", "pages", "numbers", "zip", "jpg", "jpeg", "png", "heic", "webp", "gif",
    "mov",
];

/// Where frontmatter is allowed in every repo: agent skills and Claude's settings folder
/// need it.
pub const SHARED_FRONTMATTER: [&str; 2] = ["AgentSkills/", ".claude/"];

/// Every ignore entry that applies to `tool`: the shared ones first, then the repo's.
pub fn ignores(config: &RepoConfig, tool: Tool) -> Vec<Ignore> {
    shared_ignores()
        .into_iter()
        .chain(config.ignore.iter().cloned())
        .filter(|i| i.applies(tool))
        .collect()
}

/// One generated file: its path in the repo and its full expected text.
pub struct Generated {
    pub path: &'static str,
    pub text: String,
}

/// Every file stet owns in a repo. `existing` reads a file's current text, for the parts
/// that belong to the repo.
pub fn files(config: &RepoConfig, existing: impl Fn(&str) -> Option<String>) -> Vec<Generated> {
    let mut files = vec![
        Generated {
            path: ".prettierrc.yaml",
            text: prettierrc(),
        },
        Generated {
            path: ".prettierignore",
            text: prettierignore(config),
        },
        Generated {
            path: ".markdownlint-cli2.yaml",
            text: markdownlint(config),
        },
        Generated {
            path: ".cspell.yaml",
            text: cspell(config, existing(".cspell.yaml").as_deref()),
        },
        Generated {
            path: ".mise.toml",
            text: mise(config, existing(".mise.toml").as_deref()),
        },
    ];
    if config.ci {
        files.push(Generated {
            path: ".github/workflows/static-analysis.yml",
            text: workflow(),
        });
    }
    files
}

fn comment(out: &mut String, indent: &str, reason: &str) {
    for line in wrap(reason, 88 - indent.len() - 2) {
        out.push_str(indent);
        out.push_str("# ");
        out.push_str(&line);
        out.push('\n');
    }
}

/// Greedy word wrap for comments. A blank line in the reason starts a new paragraph;
/// single line breaks are reflowed.
fn wrap(text: &str, width: usize) -> Vec<String> {
    let mut lines = vec![];
    for para in text.trim().split("\n\n") {
        let mut line = String::new();
        for word in para.split_whitespace() {
            if !line.is_empty() && line.chars().count() + 1 + word.chars().count() > width {
                lines.push(std::mem::take(&mut line));
            }
            if !line.is_empty() {
                line.push(' ');
            }
            line.push_str(word);
        }
        lines.push(line);
    }
    lines
}

/// A YAML double-quoted string.
fn quote(text: &str) -> String {
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}

fn prettierrc() -> String {
    format!(
        "{HEADER}\n\
         # proseWrap: preserve keeps prose line breaks exactly as written, never rewrapped.\n\
         # It's Prettier's default, stated because a prose repo depends on it.\n\
         proseWrap: preserve\n"
    )
}

fn prettierignore(config: &RepoConfig) -> String {
    let mut out = format!("{HEADER}\n");
    for ignore in ignores(config, Tool::Prettier) {
        out.push('\n');
        comment(&mut out, "", &ignore.reason);
        for path in &ignore.paths {
            out.push_str(path);
            out.push('\n');
        }
    }
    out
}

fn markdownlint(config: &RepoConfig) -> String {
    let mut out = format!(
        "{HEADER}\n\
         # Rules: https://github.com/DavidAnson/markdownlint/blob/main/doc/Rules.md\n\
         # Prettier is the formatter of record, so the rules it owns are off here.\n\
         config:\n  \
           default: true\n  \
           MD013: false # line length — handled by Prettier / proseWrap\n  \
           MD030: false # list-marker spacing — owned by Prettier\n  \
           MD033: false # allow inline HTML\n  \
           MD036: false # allow bold text used as a lightweight sub-heading\n  \
           MD041: false # first line need not be a top-level heading\n  \
           MD049: false # emphasis style — owned by Prettier\n  \
           MD050: false # strong style — owned by Prettier\n  \
           MD024:\n    \
             siblings_only: true # duplicate headings OK under different parents\n\
         globs:\n  \
           - \"**/*.md\"\n\
         ignores:\n  \
           - .git\n"
    );
    for ignore in ignores(config, Tool::Markdownlint) {
        comment(&mut out, "  ", &ignore.reason);
        for path in &ignore.paths {
            out.push_str("  - ");
            out.push_str(&quote(path.trim_end_matches('/')));
            out.push('\n');
        }
    }
    out
}

fn cspell(config: &RepoConfig, existing: Option<&str>) -> String {
    let mut out = format!(
        "{HEADER}\n\
         # Everything from `words:` on is this repo's own vocabulary: add jargon there under\n\
         # the comment headings, and fix real typos in the content instead.\n\
         version: \"0.2\"\n\
         language: en\n\
         useGitignore: true\n"
    );
    if !config.cspell.ignore_regexps.is_empty() {
        out.push_str("ignoreRegExpList:\n");
        for p in &config.cspell.ignore_regexps {
            comment(&mut out, "  ", &p.reason);
            out.push_str("  - ");
            out.push_str(&quote(&p.pattern));
            out.push('\n');
        }
    }
    out.push_str("ignorePaths:\n  - \".git/**\"\n");
    for ignore in ignores(config, Tool::Cspell) {
        comment(&mut out, "  ", &ignore.reason);
        for path in &ignore.paths {
            let glob = match path.strip_suffix('/') {
                Some(dir) => format!("{dir}/**"),
                None => path.clone(),
            };
            out.push_str("  - ");
            out.push_str(&quote(&glob));
            out.push('\n');
        }
    }
    comment(&mut out, "  ", "Binary formats: no prose to check.");
    for ext in BINARY {
        out.push_str(&format!("  - \"**/*.{ext}\"\n"));
    }
    out.push('\n');
    match existing.and_then(cspell_words) {
        Some(words) => out.push_str(words),
        None => out.push_str("words: []\n"),
    }
    out
}

/// The repo's own part of `.cspell.yaml`: from `words:` on, with the comment lines right
/// above it.
pub fn cspell_words(text: &str) -> Option<&str> {
    let lines: Vec<&str> = text.split_inclusive('\n').collect();
    let at = lines.iter().position(|l| l.starts_with("words:"))?;
    let mut start = at;
    while start > 0 && lines[start - 1].trim_start().starts_with('#') {
        start -= 1;
    }
    let offset: usize = lines[..start].iter().map(|l| l.len()).sum();
    Some(&text[offset..])
}

/// The repo's own part of `.mise.toml`: everything after the marker line.
pub fn mise_tail(text: &str) -> Option<&str> {
    let at = text.find(MISE_MARKER)?;
    let rest = &text[at + MISE_MARKER.len()..];
    Some(rest.strip_prefix('\n').unwrap_or(rest))
}

fn mise(config: &RepoConfig, existing: Option<&str>) -> String {
    let mut ci = vec!["ci-format-md", "spell", "markdownlint"];
    ci.extend(config.mise.check_tasks.iter().map(String::as_str));
    let depends = ci
        .iter()
        .map(|t| format!("\"{t}\""))
        .collect::<Vec<_>>()
        .join(", ");
    let mut out = format!(
        r#"{HEADER}
# The repo's own tasks go below the marker line at the end.
[tools]
node = "{NODE}"
"npm:cspell" = "{CSPELL}"
"npm:prettier" = "{PRETTIER}"
"npm:markdownlint-cli2" = "{MARKDOWNLINT}"

# The command to run before committing. stet formats, spell-checks and lints, one tool
# after another, then applies the house rules. Without stet it runs the tools alone.
[tasks.check]
description = "Format, spell-check, lint and apply the house rules (stet check)"
run = '''
if command -v stet >/dev/null 2>&1; then exec stet check; fi
if [ -x "$HOME/.local/bin/stet" ]; then exec "$HOME/.local/bin/stet" check; fi
echo "stet isn't installed: running the tools without the house rules" >&2
mise run format-md && mise run ci-static-analysis
'''

[tasks.format-md]
description = "Format all Markdown files with Prettier"
run = "prettier --write --log-level silent '**/*.md'"

# The linters read what Prettier writes. Run together, they would race it and lint
# half-written files, so they wait for it when both are scheduled.
[tasks.spell]
description = "Spell-check with cspell"
wait_for = ["format-md"]
run = "cspell lint --no-progress ."

[tasks.markdownlint]
description = "Lint all Markdown files"
wait_for = ["format-md"]
run = """
out=$(markdownlint-cli2 '**/*.md' 2>&1) && echo "Markdown lint passed" || {{ echo "$out"; exit 1; }}
"""

# CI can't install stet, so it runs the tools check-only on the committed configs.
[tasks.ci-static-analysis]
description = "Check formatting, spelling and lint without changing a file"
depends = [{depends}]

[tasks.ci-format-md]
description = "Check Markdown formatting (Prettier) without modifying files"
run = "prettier --check '**/*.md'"

{MISE_MARKER}
"#
    );
    if let Some(tail) = existing.and_then(mise_tail) {
        out.push_str(tail);
    }
    out
}

fn workflow() -> String {
    format!(
        "{HEADER}\n\
         name: Static analysis\n\
         on:\n  \
           push:\n    \
             branches: [main]\n  \
           pull_request:\n  \
           workflow_dispatch:\n\
         jobs:\n  \
           static-analysis:\n    \
             runs-on: ubuntu-latest\n    \
             steps:\n      \
               - uses: actions/checkout@v4\n      \
               - uses: jdx/mise-action@v2\n      \
               - run: mise run ci-static-analysis\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn words_keep_their_comment() {
        let text = "version: \"0.2\"\nignorePaths:\n  - x\n# Terms\n# more\nwords:\n  - a\n";
        assert_eq!(cspell_words(text), Some("# Terms\n# more\nwords:\n  - a\n"));
        assert_eq!(cspell_words("version: 1\n"), None);
    }

    #[test]
    fn cspell_keeps_words_and_round_trips() {
        let config = RepoConfig::default();
        let first = cspell(&config, Some("words:\n  - Gerry\n"));
        assert!(first.ends_with("\nwords:\n  - Gerry\n"));
        assert_eq!(cspell(&config, Some(&first)), first);
        assert!(cspell(&config, None).ends_with("words: []\n"));
    }

    #[test]
    fn mise_keeps_the_tail_and_round_trips() {
        let config = RepoConfig::default();
        let tail = "\n[tasks.books]\nrun = \"x\"\n";
        let first = mise(&config, Some(&format!("{MISE_MARKER}{tail}")));
        assert!(first.ends_with(&format!("{MISE_MARKER}\n{}", &tail[1..])));
        assert_eq!(mise(&config, Some(&first)), first);
        let parsed: toml::Table = toml::from_str(&first).unwrap();
        assert!(parsed["tasks"].get("books").is_some());
    }

    #[test]
    fn comments_wrap() {
        let mut out = String::new();
        comment(&mut out, "  ", &"word ".repeat(40));
        assert!(out.lines().all(|l| l.len() <= 88));
        assert!(out.lines().count() > 1);
    }

    #[test]
    fn markdownlint_strips_the_slash() {
        let text = markdownlint(&RepoConfig::default());
        assert!(text.contains("  - \"Inbox\"\n"));
        assert!(text.contains("  - \"**/.build\"\n"));
    }
}
