//! The shared setup, built from a repo's `.stet.toml`. This is the one copy of it.
//!
//! Two kinds of output. A few files go into each repo, because something outside stet
//! reads them: `.mise.toml` pins stet and hk, `hk.pkl` is the pre-commit hook, and the CI
//! workflow runs `stet check`. `stet sync` writes those and `stet check` fails when a copy
//! differs. The tool configs never go into the repo: stet writes them to its cache on every
//! run and hands them to the tools, so the versions and rules in this file are the ones used.
//!
//! `.cspell.yaml` is the repo's own: its words, read by stet and by editors. stet creates
//! it and never rewrites it, except once to cut an older stet's generated settings out.

use std::path::Path;

use crate::config::{Ignore, Kind, RepoConfig, Tool};

pub const HEADER: &str = "# Generated by stet from .stet.toml. Edit that file and run `stet sync`.";

/// Everything below this line in `.mise.toml` is the repo's own.
pub const MISE_MARKER: &str =
    "# ---- Below this line: this repo's own tasks. stet sync leaves them as they are. ----";

/// Everything below this line in `hk.pkl` is the repo's own steps.
pub const HK_MARKER: &str =
    "// ---- Below this line: this repo's own steps. stet sync leaves them as they are. ----";

/// What a repo's own steps are when it has none yet.
const HK_EMPTY: &str = "local repo_steps = new Mapping<String, Step> {}\n";

/// Where mise installs stet from; the repos pin this stet's own version.
pub const SOURCE: &str = "github:gshaw/stet";
pub const STET: &str = env!("CARGO_PKG_VERSION");

pub const NODE: &str = "24.4.1";
pub const CSPELL: &str = "10.4.0";
pub const PRETTIER: &str = "3.8.3";
pub const MARKDOWNLINT: &str = "0.22.1";
pub const HK: &str = "2.12.0";

/// Files an older stet generated into each repo. Now they're written to the cache, so
/// `stet sync` removes them, but only a copy that starts with [`HEADER`].
pub const LEGACY: [&str; 3] = [
    ".prettierrc.yaml",
    ".prettierignore",
    ".markdownlint-cli2.yaml",
];

/// The top of a repo's own `.cspell.yaml`.
pub const WORDS_HEADER: &str = "\
# This repo's words. stet check and editors' spell checkers both read this file; stet's
# own cspell settings come from .stet.toml. Add jargon under the comment headings, and fix
# real typos in the content instead.
";

/// Ignores every repo gets, for every tool and the house rules.
pub fn shared_ignores() -> Vec<Ignore> {
    let entry = |paths: &[&str], reason: &str| Ignore {
        paths: paths.iter().map(|p| p.to_string()).collect(),
        tools: None,
        reason: reason.into(),
    };
    vec![
        entry(&["node_modules/"], "Installed packages."),
        entry(
            &["Inbox/"],
            "The drop zone holds raw captures, not records. Never reformatted or linted in \
             place; checked once absorbed into a domain.",
        ),
        entry(
            &["**/.build/"],
            "SwiftPM build output and checkouts: other people's code.",
        ),
    ]
}

/// Files cspell skips in every repo: binary formats with no prose to check.
const BINARY: [&str; 13] = [
    "pdf", "doc", "docx", "pages", "numbers", "zip", "jpg", "jpeg", "png", "heic", "webp", "gif",
    "mov",
];

/// Where frontmatter is allowed in every repo: agent skills, Claude's settings folder and
/// GitHub's issue templates need it.
pub const SHARED_FRONTMATTER: [&str; 3] = ["AgentSkills/", ".claude/", ".github/"];

/// Every ignore entry that applies to `tool`: the shared ones first, then the repo's.
pub fn ignores(config: &RepoConfig, tool: Tool) -> Vec<Ignore> {
    shared_ignores()
        .into_iter()
        .chain(config.ignore.iter().cloned())
        .filter(|i| i.applies(tool))
        .collect()
}

/// One file stet keeps in a repo: its path and its full expected text.
pub struct Generated {
    pub path: &'static str,
    pub text: String,
}

/// Every file stet keeps in a repo. `existing` reads a file's current text, for the parts
/// that belong to the repo.
pub fn files(config: &RepoConfig, existing: impl Fn(&str) -> Option<String>) -> Vec<Generated> {
    let mut files = vec![Generated {
        path: ".cspell.yaml",
        text: words(existing(".cspell.yaml").as_deref()),
    }];
    // A code repo's mise.toml is its own; it pins stet and hk by hand (`stet check` says
    // when they're behind).
    if config.kind == Kind::Notes {
        files.push(Generated {
            path: ".mise.toml",
            text: mise(config, existing(".mise.toml").as_deref()),
        });
    }
    files.push(Generated {
        path: "hk.pkl",
        text: hk(config.kind, existing("hk.pkl").as_deref()),
    });
    if config.ci() {
        files.push(Generated {
            path: ".github/workflows/static-analysis.yml",
            text: workflow(),
        });
    }
    files
}

/// True for a file an older stet generated, which `stet sync` may remove or rewrite.
pub fn is_generated(text: &str) -> bool {
    text.starts_with(HEADER)
}

fn comment(out: &mut String, indent: &str, reason: &str) {
    for line in wrap(reason, 88 - indent.len() - 2) {
        out.push_str(indent);
        out.push_str("# ");
        out.push_str(&line);
        out.push('\n');
    }
}

/// Greedy word wrap for comments. A blank line in the reason starts a new paragraph;
/// single line breaks are reflowed.
fn wrap(text: &str, width: usize) -> Vec<String> {
    let mut lines = vec![];
    for para in text.trim().split("\n\n") {
        let mut line = String::new();
        for word in para.split_whitespace() {
            if !line.is_empty() && line.chars().count() + 1 + word.chars().count() > width {
                lines.push(std::mem::take(&mut line));
            }
            if !line.is_empty() {
                line.push(' ');
            }
            line.push_str(word);
        }
        lines.push(line);
    }
    lines
}

/// A YAML double-quoted string.
fn quote(text: &str) -> String {
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}
/// The repo's `.cspell.yaml`: kept as it is, created when missing, and cut down to its
/// words when an older stet generated it.
fn words(existing: Option<&str>) -> String {
    match existing {
        Some(text) if !is_generated(text) => text.to_string(),
        Some(text) => match cspell_words(text) {
            Some(words) => format!("{WORDS_HEADER}\n{words}"),
            None => format!("{WORDS_HEADER}\nwords: []\n"),
        },
        None => format!("{WORDS_HEADER}\nwords: []\n"),
    }
}

/// The part of an older generated `.cspell.yaml` that was the repo's: from `words:` on,
/// with the comment lines right above it.
pub fn cspell_words(text: &str) -> Option<&str> {
    let lines: Vec<&str> = text.split_inclusive('\n').collect();
    let at = lines.iter().position(|l| l.starts_with("words:"))?;
    let mut start = at;
    while start > 0 && lines[start - 1].trim_start().starts_with('#') {
        start -= 1;
    }
    let offset: usize = lines[..start].iter().map(|l| l.len()).sum();
    Some(&text[offset..])
}

/// The repo's own part of `.mise.toml`: everything after the marker line.
pub fn mise_tail(text: &str) -> Option<&str> {
    let at = text.find(MISE_MARKER)?;
    let rest = &text[at + MISE_MARKER.len()..];
    Some(rest.strip_prefix('\n').unwrap_or(rest))
}

fn mise(_config: &RepoConfig, existing: Option<&str>) -> String {
    let mut out = format!(
        r#"{HEADER}
# The repo's own tasks go below the marker line at the end.
# stet brings its own Prettier, cspell and markdownlint; this repo pins only stet and hk.

# mise's version service (mise-versions.jdx.dev) doesn't list stet, so ask GitHub directly.
[settings]
use_versions_host = false

[tools]
"{SOURCE}" = "{STET}"
hk = "{HK}"

# The command to run before committing: format, spell-check, lint, then the house rules.
[tasks.check]
description = "Format, spell-check, lint and apply the house rules (stet check)"
run = "stet check"

{MISE_MARKER}
"#
    );
    if let Some(tail) = existing.and_then(mise_tail) {
        out.push_str(tail);
    }
    out
}

/// The repo's own part of `hk.pkl`: everything after the marker line.
pub fn hk_tail(text: &str) -> Option<&str> {
    let at = text.find(HK_MARKER)?;
    let rest = &text[at + HK_MARKER.len()..];
    Some(rest.strip_prefix('\n').unwrap_or(rest))
}

/// Every repo's hooks: one pre-commit hook, check-only and no stash, because sessions
/// share working trees and a stash would move their edits off disk. In a knowledge repo
/// the stet step checks the whole repo, so a rename that breaks another note's link, or a
/// word dropped from `.cspell.yaml`, fails the commit; the hook is the only check there.
/// In a code repo it reports findings only in the staged files, and CI checks the rest.
/// The repo's own steps (rustfmt, SwiftLint) go below the marker; `hk check` and `hk fix`
/// run them all.
fn hk(kind: Kind, existing: Option<&str>) -> String {
    let header = HEADER.replacen('#', "//", 1);
    let tail = existing.and_then(hk_tail).unwrap_or(HK_EMPTY);
    let (scope, files) = match kind {
        Kind::Notes => ("the whole repo", ""),
        Kind::Code => ("the staged files only", " --files {{files}}"),
    };
    format!(
        r#"{header}
// Every repo's pre-commit hook: check-only, no stash, {scope}. hk's global
// hook in ~/.gitconfig runs it. `hk fix --all` fixes what it can. The repo's own steps go
// below the marker line at the end, as `repo_steps`.
amends "package://github.com/jdx/hk/releases/download/v{HK}/hk@{HK}#/Config.pkl"
import "package://github.com/jdx/hk/releases/download/v{HK}/hk@{HK}#/Builtins.pkl"

hooks {{
  ["pre-commit"] {{
    fix = false
    stash = "none"
  }}
}}

steps {{
  ["stet"] {{
    check = "stet check --check-only{files}"
    fix = "stet check{files}"
  }}
  ...repo_steps
}}

{HK_MARKER}
{tail}"#
    )
}

fn workflow() -> String {
    format!(
        "{HEADER}\n\
         name: Static analysis\n\
         on:\n  \
           push:\n    \
             branches: [main]\n  \
           pull_request:\n  \
           workflow_dispatch:\n\
         jobs:\n  \
           static-analysis:\n    \
             runs-on: ubuntu-latest\n    \
             steps:\n      \
               - uses: actions/checkout@v4\n      \
               - uses: jdx/mise-action@v2\n      \
               - run: stet check --check-only\n"
    )
}

// ---- The tool configs: written to stet's cache on every run, never into the repo. ----

/// Prettier's arguments after `--write` or `--check`: stet's settings in place of any
/// config file, every Markdown file, and the ignores as negated globs. Prettier skips
/// `.gitignore`d files and `node_modules` on its own.
pub fn prettier_args(config: &RepoConfig) -> Vec<String> {
    let mut args: Vec<String> = ["--no-config", "--prose-wrap", "preserve", "**/*.md"]
        .map(String::from)
        .into();
    for ignore in ignores(config, Tool::Prettier) {
        for path in &ignore.paths {
            args.push(format!("!{}", glob(path)));
        }
    }
    args
}

/// A gitignore-style path as a glob from the repo root: `Inbox/` matches at any depth, as
/// it does in a `.prettierignore`, and a folder means everything in it.
fn glob(path: &str) -> String {
    let anchored = path.starts_with('/');
    let path = path.trim_start_matches('/');
    let (body, dir) = match path.strip_suffix('/') {
        Some(body) => (body, true),
        None => (path, false),
    };
    let mut out = if anchored || body.contains('/') {
        body.to_string()
    } else {
        format!("**/{body}")
    };
    if dir {
        out.push_str("/**");
    }
    out
}

/// markdownlint-cli2's globs: every Markdown file, and each ignore as a `#` glob. A bare
/// name like `node_modules/` matches at any depth, as it does for Prettier.
pub fn markdownlint_globs(config: &RepoConfig) -> Vec<String> {
    let mut args = vec!["**/*.md".to_string(), "#.git".to_string()];
    for ignore in ignores(config, Tool::Markdownlint) {
        for path in &ignore.paths {
            args.push(format!("#{}", glob(path)));
        }
    }
    args
}

/// markdownlint's rules, passed with `--config`. It skips `.gitignore`d files, as Prettier
/// and cspell do, so a code repo's `deps/` and `_build/` need no ignore entry.
pub fn markdownlint_config() -> String {
    format!(
        "{HEADER}\n\
         # Rules: https://github.com/DavidAnson/markdownlint/blob/main/doc/Rules.md\n\
         # Prettier is the formatter of record, so the rules it owns are off here.\n\
         gitignore: true\n\
         config:\n  \
           default: true\n  \
           MD013: false # line length — handled by Prettier / proseWrap\n  \
           MD030: false # list-marker spacing — owned by Prettier\n  \
           MD033: false # allow inline HTML\n  \
           MD036: false # allow bold text used as a lightweight sub-heading\n  \
           MD041: false # first line need not be a top-level heading\n  \
           MD049: false # emphasis style — owned by Prettier\n  \
           MD050: false # strong style — owned by Prettier\n  \
           MD024:\n    \
             siblings_only: true # duplicate headings OK under different parents\n"
    )
}

/// cspell's settings, passed with `-c`. They import the repo's `.cspell.yaml` for its
/// words. `globRoot` makes the ignore paths start at the repo, where cspell runs, not at
/// this file in the cache. No `language`: cspell's default is `en`, and a repo that wants
/// another (`en,en-GB`) sets it in its own `.cspell.yaml`, where an editor sees it too.
pub fn cspell_config(config: &RepoConfig, root: &Path) -> String {
    let mut out = format!(
        "{HEADER}\n\
         version: \"0.2\"\n\
         globRoot: \"${{cwd}}\"\n\
         useGitignore: true\n"
    );
    let words = root.join(".cspell.yaml");
    if words.is_file() {
        out.push_str("import:\n  - ");
        out.push_str(&quote(&words.display().to_string()));
        out.push('\n');
    }
    if !config.cspell.ignore_regexps.is_empty() {
        out.push_str("ignoreRegExpList:\n");
        for p in &config.cspell.ignore_regexps {
            comment(&mut out, "  ", &p.reason);
            out.push_str("  - ");
            out.push_str(&quote(&p.pattern));
            out.push('\n');
        }
    }
    out.push_str("ignorePaths:\n  - \".git/**\"\n");
    for ignore in ignores(config, Tool::Cspell) {
        comment(&mut out, "  ", &ignore.reason);
        for path in &ignore.paths {
            let glob = match path.strip_suffix('/') {
                Some(dir) => format!("{dir}/**"),
                None => path.clone(),
            };
            out.push_str("  - ");
            out.push_str(&quote(&glob));
            out.push('\n');
        }
    }
    comment(&mut out, "  ", "Binary formats: no prose to check.");
    for ext in BINARY {
        out.push_str(&format!("  - \"**/*.{ext}\"\n"));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn words_keep_their_comment() {
        let text = "version: \"0.2\"\nignorePaths:\n  - x\n# Terms\n# more\nwords:\n  - a\n";
        assert_eq!(cspell_words(text), Some("# Terms\n# more\nwords:\n  - a\n"));
        assert_eq!(cspell_words("version: 1\n"), None);
    }

    #[test]
    fn an_old_generated_cspell_becomes_its_words() {
        let old = format!(
            "{HEADER}\nversion: \"0.2\"\nignorePaths:\n  - x\n\n# Ours\nwords:\n  - Gerry\n"
        );
        let new = words(Some(&old));
        assert_eq!(new, format!("{WORDS_HEADER}\n# Ours\nwords:\n  - Gerry\n"));
        assert_eq!(words(Some(&new)), new);
        assert_eq!(words(Some("words: [a]\n")), "words: [a]\n");
        assert!(words(None).ends_with("words: []\n"));
    }

    #[test]
    fn mise_keeps_the_tail_and_round_trips() {
        let config = RepoConfig::default();
        let tail = "\n[tasks.books]\nrun = \"x\"\n";
        let first = mise(&config, Some(&format!("{MISE_MARKER}{tail}")));
        assert!(first.ends_with(&format!("{MISE_MARKER}\n{}", &tail[1..])));
        assert_eq!(mise(&config, Some(&first)), first);
        let parsed: toml::Table = toml::from_str(&first).unwrap();
        assert!(parsed["tasks"].get("books").is_some());
        assert_eq!(parsed["tools"][SOURCE].as_str(), Some(STET));
        assert_eq!(
            parsed["settings"]["use_versions_host"].as_bool(),
            Some(false)
        );
    }

    #[test]
    fn notes_hook_checks_the_whole_repo_and_code_hook_the_staged_files() {
        let notes = hk(Kind::Notes, None);
        assert!(notes.contains(r#"check = "stet check --check-only""#));
        assert!(notes.contains(r#"fix = "stet check""#));
        let code = hk(Kind::Code, None);
        assert!(code.contains(r#"check = "stet check --check-only --files {{files}}""#));
        assert!(code.contains(r#"fix = "stet check --files {{files}}""#));
    }

    #[test]
    fn comments_wrap() {
        let mut out = String::new();
        comment(&mut out, "  ", &"word ".repeat(40));
        assert!(out.lines().all(|l| l.len() <= 88));
        assert!(out.lines().count() > 1);
    }

    #[test]
    fn globs_follow_gitignore() {
        assert_eq!(glob("Inbox/"), "**/Inbox/**");
        assert_eq!(glob("**/.build/"), "**/.build/**");
        assert_eq!(glob("Writing/pieces/"), "Writing/pieces/**");
        assert_eq!(glob("Journal/Diary/2*.md"), "Journal/Diary/2*.md");
        assert_eq!(glob("/top.md"), "top.md");
        assert_eq!(glob("*.eml"), "**/*.eml");
    }

    #[test]
    fn markdownlint_ignores_match_at_any_depth() {
        let globs = markdownlint_globs(&RepoConfig::default());
        assert!(globs.contains(&"#**/Inbox/**".to_string()));
        assert!(globs.contains(&"#**/node_modules/**".to_string()));
        assert!(globs.contains(&"#**/.build/**".to_string()));
    }
}
